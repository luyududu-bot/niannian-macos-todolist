const assert=require('node:assert/strict');
const N=require('../源码/model.js');
const R=require('../源码/reminders-sync.js');
const at=N.day(),finished=at+'T12:00:00',past='2020-01-01';
const rows=[{id:'history',kind:'daily',day:past,completedAt:past+'T12:00:00'}, {id:'a',kind:'daily',day:at,title:'a'}, {id:'long-a',kind:'long'}, {id:'b',kind:'daily',day:past,title:'b'}, {id:'done-a',kind:'daily',day:at,completedAt:finished}, {id:'c',kind:'daily',day:at,parentId:'long-a'}, {id:'long-b',kind:'long'}, {id:'done-b',kind:'daily',day:at,completedAt:finished}, {id:'future',kind:'daily',day:'2099-01-01'}];
const original=JSON.stringify(rows),ids=x=>x.map(t=>t.id);
let sorted=N.reorder(rows,'c','a',false,at);
assert.deepEqual(ids(sorted),['history','c','long-a','a','done-a','b','long-b','done-b','future']);
assert.equal(sorted[1],rows[5]);assert.equal(sorted[1].parentId,'long-a');
assert.equal(JSON.stringify(rows),original);
assert.deepEqual(ids(N.reorder(rows,'a','c',true,at)),['history','b','long-a','c','done-a','a','long-b','done-b','future']);
assert.deepEqual(ids(N.reorder(rows,'long-b','long-a',false,at)),['history','a','long-b','b','done-a','c','long-a','done-b','future']);
assert.equal(N.reorder(rows,'a','long-a',false,at),rows);
assert.equal(N.reorder(rows,'a','done-a',false,at),rows);
assert.equal(N.reorder(rows,'a','future',false,at),rows);
assert.equal(N.reorder(rows,'a','history',false,at),rows);
assert.equal(N.reorder(rows,'missing','b',false,at),rows);
assert.equal(N.reorder(rows,'a','a',false,at),rows);
assert.deepEqual(ids(N.reorder(rows,'done-b','done-a',false,at)),['history','a','long-a','b','done-b','c','long-b','done-a','future']);
console.log('排序通过：上下移动、长期、已完成分组、历史隔离、无效目标、任务内容不变');

const clean=[{id:'a',title:'First',kind:'daily',day:at,completedAt:null},{id:'b',title:'Second',kind:'daily',day:at,completedAt:null}];
const ordered=N.reorder(clean,'b','a',false,at);
const snapshot={meta:{links:{a:'ra',b:'rb'},base:Object.fromEntries(clean.map(t=>[t.id,R.fields(t)]))},rows:clean.map(t=>({...t,remoteId:'r'+t.id}))};
let synced=R.plan({tasks:ordered},snapshot,new Date());
assert.deepEqual(ids(synced.state.tasks),['b','a']);assert.equal(synced.ops.length,0);
snapshot.rows[0].title='Updated on phone';synced=R.plan({tasks:ordered},snapshot,new Date());
assert.deepEqual(ids(synced.state.tasks),['b','a']);assert.equal(synced.state.tasks[1].title,'Updated on phone');
console.log('PASS: manual order survives sync and remote title edits without generating ordering writes');
